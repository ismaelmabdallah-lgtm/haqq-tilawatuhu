"""Generate supabase/seed/0001_minhaj_al_darisin.sql from a curriculum map.

Usage: python3 scripts/generate_seed.py [path/to/curriculum-map.json]

IDs are deterministic (md5 of a stable key) so the seed is idempotent and other
seed files can reference rows without lookups. Structure (levels, chapters) is
published because it is the book's own table of contents; every lesson is a
DRAFT with empty content and a source page reference, so nothing reaches
students before extraction and scientific review.
"""
import json
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "content/curricula/minhaj-al-darisin-ed2-2026/curriculum-map.json"
OUT = "supabase/seed/0001_minhaj_al_darisin.sql"


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def uid(key):
    return f"md5({q('haqq:' + key)})::uuid"


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    c, ed = d["curriculum"], d["curriculum"]["edition"]
    cid, eid = c["curriculum_id"], ed["edition_id"]
    out = [
        "-- GENERATED by scripts/generate_seed.py — do not edit by hand.",
        f"-- Source: {SRC}",
        "begin;",
        "insert into public.riwayat (id, code, name_ar, name_en, tariq) values",
        f"  ({uid('riwayah:hafs-asim-shatibiyyah')}, 'hafs-asim-shatibiyyah', 'حفص عن عاصم', 'Hafs an Asim', 'الشاطبية')",
        "on conflict (code) do nothing;",
        "",
        "insert into public.curricula (id, slug, title, description, language, country_code, is_published, affiliation_note) values",
        f"  ({uid('curriculum:' + cid)}, {q(cid)}, {q(c['title'])}, {q(c['subtitle'])}, 'ar', 'JO', true, {q(c['affiliation_note'])})",
        "on conflict (slug) do nothing;",
        "",
        "insert into public.curriculum_editions (id, curriculum_id, slug, label, year_ce, year_ah, riwayah_id, publisher, authors, source_document, is_published, is_current) values",
        f"  ({uid('edition:' + eid)}, {uid('curriculum:' + cid)}, {q(eid)}, {q(ed['label'])}, {ed['year_ce']}, {ed['year_ah']},",
        f"   {uid('riwayah:hafs-asim-shatibiyyah')}, {q(c['publisher'])}, array[{', '.join(q(a) for a in c['authors'])}]::text[],",
        f"   {q({**c['source_document'], 'national_library_deposit': ed['national_library_deposit'], 'extraction_notes': d['extraction_notes']})}, true, true)",
        "on conflict do nothing;",
        "",
    ]
    rows = []
    for lv in d["levels"]:
        rows.append(f"  ({uid('level:' + eid + ':' + lv['level_id'])}, {uid('edition:' + eid)}, {q(lv['level_id'])}, {lv['order']}, "
                    f"{q(lv['title'])}, {q(lv['subtitle'])}, {lv['source_page_start']}, {lv['source_page_end']})")
    out += ["insert into public.levels (id, edition_id, code, sort_order, title, subtitle, source_page_start, source_page_end) values",
            ",\n".join(rows), "on conflict do nothing;", ""]
    rows = []
    for lv in d["levels"]:
        for ch in lv["chapters"]:
            rows.append(f"  ({uid('chapter:' + eid + ':' + ch['chapter_id'])}, {uid('level:' + eid + ':' + lv['level_id'])}, "
                        f"{q(ch['chapter_id'])}, {ch['order']}, {q(ch['label'])}, {q(ch['title'])}, "
                        f"{ch['source_page_start']}, {ch['source_page_end']}, {q(ch['review_note'])})")
    out += ["insert into public.chapters (id, level_id, code, sort_order, label, title, source_page_start, source_page_end, review_note) values",
            ",\n".join(rows), "on conflict do nothing;", ""]
    rows = []
    for l in d["lessons"]:
        parent = uid("lesson:" + eid + ":" + l["parent_id"]) if l["parent_id"] else "null"
        rows.append(f"  ({uid('lesson:' + eid + ':' + l['lesson_id'])}, {uid('chapter:' + eid + ':' + l['chapter_id'])}, {parent}, "
                    f"{q(l['lesson_id'])}, {l['order']}, {q(l['title'])}, 'curriculum_quoted', {uid('edition:' + eid)}, "
                    f"{l['source_page_start']}, {l['source_page_end']})")
    out += ["-- All lessons start as drafts (enforced by tg_content_guard).",
            "insert into public.lessons (id, chapter_id, parent_lesson_id, code, sort_order, title, origin, source_edition_id, source_page_start, source_page_end) values",
            ",\n".join(rows), "on conflict do nothing;", "commit;", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote {OUT}: {len(d['levels'])} levels, {sum(len(x['chapters']) for x in d['levels'])} chapters, {len(d['lessons'])} lessons")


if __name__ == "__main__":
    main()
